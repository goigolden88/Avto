/**
 * Числа, написанные в коде цифрами, — без комментариев: там цифры —
 * номера решений и пояснения, на экран они не идут. Цифра внутри имени
 * (`h1`) — не число. Справка берёт числа из констант экранов, и цифра в её
 * тексте — число, которое разойдётся с экраном, когда константа поменяется.
 */
function typedNumbers(code: string): string[] {
  const bare = code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')
  return [...bare.matchAll(/[^\n]{0,30}(?<![\p{L}\w])\d[^\n]{0,30}/gu)].map((match) => match[0].trim())
}

/** Текст без переносов строк: название, разорванное переносом в JSX, на экране цельное. */
const flat = (text: string) => text.replace(/\s+/g, ' ')

