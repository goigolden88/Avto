describe('справка', () => {
  it('поиск чисел находит цифры в тексте и не смотрит в комментарии', () => {
    expect(typedNumbers('<p>Замер дольше 12 часов</p>')).toEqual(['<p>Замер дольше 12 часов</p>'])
    expect(typedNumbers('<p>Замер дольше {TIMER_LIMIT_TEXT}</p>')).toEqual([])
    expect(typedNumbers('// Р-30\n/* Р-02 */ <h1>текст</h1>')).toEqual([])
    expect(typedNumbers('<p>{count > 0 && count}</p>')).toEqual(['<p>{count > 0 && count}</p>'])
  })

  it('цифрами в справке ничего не написано — числа из констант экранов', () => {
    expect(typedNumbers(source)).toEqual([])
  })

  it('разделы — экраны, данные и «если что-то не так», все свёрнуты', () => {
    const titles = [...source.matchAll(/<Fold [^>]*title="([^"]+)"/g)].map((match) => match[1])
    expect(titles).toEqual(SECTIONS)
    const folds = [...source.matchAll(/<Fold [^>]*>/g)].map((match) => match[0])
    expect(folds.every((fold) => / folded>$/.test(fold))).toBe(true)
  })

  it('названия кнопок, блоков и полей — те же, что на экранах', () => {
    const missing = NAMED.filter((name) => !SCREENS.some((text) => flat(text).includes(name)))
    expect(missing).toEqual([])
    const unused = NAMED.filter((name) => !flat(source).includes(name))
    expect(unused).toEqual([])
  })

  it('список названий — в кавычках, через запятую и последнее через союз', () => {
    expect(listText([])).toBe('')
    expect(listText(['Месяц'])).toBe('«Месяц»')
    expect(listText(['Месяц', 'Год', 'Всё'])).toBe('«Месяц», «Год» и «Всё»')
    expect(listText(['сразу', 'мест нет'], 'или')).toBe('«сразу» или «мест нет»')
  })
})
