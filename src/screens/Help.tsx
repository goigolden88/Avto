/** «а», «б» и «в» — названия кнопок и видов списком, как в тексте. */
export function listText(labels: readonly string[], word = 'и'): string {
  const quoted = labels.map((label) => `«${label}»`)
  const last = quoted.pop()
  if (last === undefined) return ''
  return quoted.length ? `${quoted.join(', ')} ${word} ${last}` : last
}

